def _d(val: float, lo: float = 0.5) -> float:
    return round(max(lo, val), 1)


def _task(
    tid: str,
    wbs: str,
    name: str,
    phase: str,
    duration_days: float,
    predecessors: list[str],
    procedures: list[str],
    materials: list[dict[str, Any]],
    labor_krw: float,
    equip_krw: float,
    risk_high: float = 1.25,
) -> dict[str, Any]:
    return {
        "task_id": tid,
        "wbs": wbs,
        "name": name,
        "phase": phase,
        "duration_days": _d(duration_days),
        "predecessors": predecessors,
        "procedures": procedures,
        "materials": materials,
        "labor_cost_krw": round(max(0.0, labor_krw), 0),
        "equipment_cost_krw": round(max(0.0, equip_krw), 0),
        "risk_low": 0.90,
        "risk_high": risk_high,
    }


def _mat(
    code: str, name: str, unit: str, qty: float, loss_rate: float, unit_price: float
) -> dict[str, Any]:
    return {
        "code": code,
        "name": name,
        "unit": unit,
        "qty": round(max(0.0, qty), 3),
        "loss_rate": loss_rate,
        "unit_price_krw": unit_price,
    }


def list_templates() -> list[dict[str, Any]]:
    return [
        {
            "domain": code,
            "name": meta["name"],
            "default_unit": meta["default_unit"],
            "description": meta["description"],
            "supported_modes": ["NEW_BUILD", "INSTALL", "REPLACE", "DEMOLISH", "RENOVATE"],
        }
        for code, meta in DOMAIN_META.items()
    ]


