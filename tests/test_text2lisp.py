def test_draw_api(client, world, monkeypatch):
    from backend.api import routes_copilot
    from core.copilot import llm

    h = world.h["designer"]
    post = lambda text, who=h: client.post("/api/copilot/draw", json={"text": text}, headers=who)
    r = post("100x50 사각형").json()["data"]
    assert r["source"] == "RULE" and '(command "REC"' in r["lisp"] and r["error"] is None
    r = post("지름 원").json()["data"]
    assert r["source"] == "RULE" and r["lisp"] is None and "지름" in r["error"]
    monkeypatch.setattr(llm, "provider", lambda var: None)
    r = post("집 모양을 그려 줘").json()["data"]
    assert r["source"] == "NONE" and "LLM을 켜면" in r["error"]

    sent: list[str] = []

    class Fake:
        name, model = "fake", "m1"

        def lisp(self, sentence):
            sent.append(sentence)
            if "실패" in sentence:
                raise llm.LlmError("LLM 서버에 연결하지 못했습니다")
            return '(command "L" (list 0 0) (list 50 50) "")'

    monkeypatch.setattr(llm, "provider", lambda var: Fake())
    monkeypatch.setattr(llm, "LIMIT", llm.RateLimit())
    r = post("집 모양을\n그려 줘 a@b.com").json()["data"]
    assert r["source"] == "LLM" and r["lisp"].startswith('(command "L"') and r["model"] == "m1"
    assert sent == ["집 모양을 그려 줘 ***"]  # one line, the e-mail address scrubbed
    r = post("실패하는 문장").json()["data"]
    assert r["source"] == "NONE" and "연결하지 못했습니다" in r["error"]
    # the LLM spends the administrator's key: a viewer gets the rules only
    r = post("집 모양을 그려 줘", world.h["viewer"]).json()["data"]
    assert r["source"] == "NONE" and len(sent) == 2
    assert routes_copilot.text2lisp.MAX_TEXT == 500
    assert client.post("/api/copilot/draw", json={"text": "x" * 501}, headers=h).status_code == 422


def test_draw_api_3d(client, world):
    h = world.h["designer"]
    post = lambda text: client.post(
        "/api/copilot/draw", json={"text": text, "page": "model3d"}, headers=h
    ).json()["data"]
    r = post("100x50x20 상자 그리고 위에 지름 20 높이 30 원통")
    assert r["source"] == "RULE" and '(command "CYLINDER" 10 30 (list 0 0 20))' in r["lisp"]
    r = post("M8 탭 구멍 4개")  # not a primitive: the hole wizard proposal
    assert r["action"]["kind"] == "dialog" and r["action"]["dialog"] == "HOLE"
    r = post("M10x30 볼트 8개")
    assert r["action"]["kind"] == "feature" and r["action"]["params"]["qty"] == 8
    assert "상자 크기" in post("상자")["error"]
    assert post("안녕")["source"] == "NONE"
