def fixture() -> list[dict[str, object]]:
    out = []
    for text, expect in EXAMPLES:
        r = parse(text)
        assert r is not None and "lisp" in r, (text, r)
        out.append({"text": text, "lisp": r["lisp"], "summary": r["summary"], "expect": expect})
    return out


